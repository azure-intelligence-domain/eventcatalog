import { existsSync, readFileSync } from 'node:fs';

// Contracts discovered in the GitHub organisation by scripts/discover-sources.mjs.
// Every repository with the topic "eventcatalog" and a release is picked up automatically,
// so adding a service never requires a change here (composable, ADR 0006).
const SOURCES_FILE = new URL('./sources.json', import.meta.url);
const sources = existsSync(SOURCES_FILE) ? JSON.parse(readFileSync(SOURCES_FILE, 'utf8')) : [];

const GENERATORS = {
  asyncapi: '@eventcatalog/generator-asyncapi',
  openapi: '@eventcatalog/generator-openapi',
};

// One generator run per contract type and domain: the generators attach services to one domain.
function generators() {
  const groups = new Map();
  for (const source of sources) {
    const key = `${source.kind}:${source.domain.id}`;
    if (!groups.has(key)) groups.set(key, { kind: source.kind, domain: source.domain, services: [] });
    groups.get(key).services.push({
      id: source.service,
      // A service's version is its repository's release: its OpenAPI and AsyncAPI contracts may
      // carry different versions, but they are released (and cataloged) together.
      version: source.release.replace(/^v/, ''),
      path: source.path,
      owners: source.owners,
      draft: source.draft, // 0.x releases are designs, not live services
    });
  }
  return [...groups.values()].map(({ kind, domain, services }) => [
    GENERATORS[kind],
    { services, domain: { ...domain, version: '1.0.0' } },
  ]);
}

